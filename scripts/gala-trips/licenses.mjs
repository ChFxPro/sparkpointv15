// Writes <trip>/pack/LICENSES.md from the pack's own manifests, so the log
// always matches what was actually used: stills/stills.json and, once the
// video is cut, video/sources.json.
import { readFile, writeFile } from 'node:fs/promises';
import { exists, packDir } from './lib.mjs';

async function readJson(path) {
  return (await exists(path)) ? JSON.parse(await readFile(path, 'utf8')) : null;
}

const SA_NOTE = 'CC BY-SA files are resized or cropped here; those adaptations are shared under the same licence.';

export async function writeLicenses(trip) {
  const stills = await readJson(packDir(trip.id, 'stills', 'stills.json'));
  const video = await readJson(packDir(trip.id, 'video', 'sources.json'));
  const lines = [
    `# ${trip.title}: media sources and licences`,
    '',
    'Generated by `scripts/gala-trips/` in the website repo. Every file in this pack that is not SparkPoint\'s own',
    'artwork is listed here with its source, author and licence. Credit lines for public use are in the "Credit" column.',
    '',
  ];
  if (stills?.stills?.length) {
    lines.push('## Stills (`stills/`)', '', '| File | Place | Credit | Licence | Source |', '| --- | --- | --- | --- | --- |');
    for (const s of stills.stills) {
      const src = s.source;
      lines.push(`| \`${s.file}-{800,1600,2400}.webp\`${s.hero ? ' (hero)' : ''} | ${s.place} | ${src.author} | [${src.license}](${src.licenseUrl || src.page}) | [${src.title}](${src.page}) |`);
    }
    if (stills.stills.some((s) => /SA/.test(s.source.license))) lines.push('', SA_NOTE);
    lines.push('');
  }
  if (video?.clips?.length) {
    lines.push('## Video footage (`video/`)', '', '| Clip | Shows | Author | Licence | Source | Used |', '| --- | --- | --- | --- | --- | --- |');
    for (const c of video.clips) lines.push(`| ${c.id} | ${c.shows} | ${c.author} | [${c.license}](${c.licenseUrl || c.page}) | [${c.title}](${c.page}) | ${c.used ?? ''} |`);
    if (video.music) lines.push('', `Music: ${video.music.title} by ${video.music.author}, ${video.music.license} ([source](${video.music.page})).`);
    lines.push('');
  }
  lines.push('## SparkPoint artwork', '', 'The lockup, sparkmark, title cards, journey map and layouts are SparkPoint\'s own (A World of Connections brand kit).', 'The map\'s land outline is from Natural Earth (public domain) via the website\'s `world-dots.svg`.', '');
  await writeFile(packDir(trip.id, 'LICENSES.md'), lines.join('\n'));
}
