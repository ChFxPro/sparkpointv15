// Builds the show deck into show/deck.js + show/deck.css.
//
// The show folder has to open straight from disk (file://) on the show laptop,
// with no server and no internet, so:
//   - the code is one classic script (no ES modules: Chrome blocks those on file://)
//   - fonts and the sparkmark are inlined as data URLs (Chrome blocks file:// font loads)
//   - the land dots for the globe are read from the site's world-dots.svg at build time
//
// Usage: npm run build   (or npm run watch while working on it)
import * as esbuild from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');

// --- Land dots -----------------------------------------------------------
// world-dots.svg is equirectangular, 1000 units wide, cropped to 78°N–58°S
// (see src/pages/GalaRouteMap.tsx). Each dot is an "Mx yh0" move.
const svg = readFileSync(resolve(repo, 'public/assets/events/gala/world-dots.svg'), 'utf8');
const W = 1000;
const TOP = 78;
const BOTTOM = -58;
const H = ((TOP - BOTTOM) / 360) * W;
const coords = [];
for (const m of svg.matchAll(/M([\d.]+) ([\d.]+)h0/g)) {
  const x = Number(m[1]);
  const y = Number(m[2]);
  const lon = (x / W) * 360 - 180;
  const lat = TOP - (y / H) * (TOP - BOTTOM);
  coords.push(Math.round(lon * 10) / 10, Math.round(lat * 10) / 10);
}
mkdirSync(resolve(here, 'src/generated'), { recursive: true });
writeFileSync(
  resolve(here, 'src/generated/land.js'),
  `// Generated by build.mjs from public/assets/events/gala/world-dots.svg. Do not edit.\n` +
    `export const LAND = new Float32Array(${JSON.stringify(coords)});\n`
);

// --- Bundle --------------------------------------------------------------
const options = {
  entryPoints: { deck: resolve(here, 'src/main.js') },
  outdir: resolve(here, 'show'),
  bundle: true,
  format: 'iife',
  target: 'chrome110',
  minify: true,
  legalComments: 'none',
  loader: { '.woff2': 'dataurl', '.webp': 'dataurl', '.png': 'dataurl' },
  logLevel: 'info',
};

// The background renderer for the template kit (kit/make-kit.mjs). It stays
// out of show/ so the show folder holds only what the night needs.
const plateOptions = {
  ...options,
  entryPoints: { plate: resolve(here, 'src/plate.js') },
  outdir: resolve(here, 'kit/.build'),
};
mkdirSync(plateOptions.outdir, { recursive: true });
writeFileSync(
  resolve(plateOptions.outdir, 'plate.html'),
  '<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="plate.css"></head><body style="margin:0;overflow:hidden"><script src="plate.js"></script></body></html>\n'
);

if (process.argv.includes('--watch')) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
} else {
  await esbuild.build(options);
  await esbuild.build(plateOptions);
  console.log(`land dots: ${coords.length / 2}`);
}
